const fieldProblems = (fields) => fields
  .map(({ field, constraints = [] }) => {
    const said = constraints.map((c) => CONSTRAINT_TEXT[c] ?? c);
    return said.length > 0 ? `${field}(${said.join(', ')})` : field;
  })
  .join(', ');

