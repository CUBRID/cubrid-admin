#!/usr/bin/env node
/**
 * Builds the server executables as Node.js single executable applications (SEA):
 * the official Node.js binary for each target with the API server bundle
 * (dist/apps/api-server/main.js) and the web screens (dist/apps/api-server/public)
 * injected into it.
 *
 *   dist/executables/cubrid-admin-linux        linux-x64
 *   dist/executables/cubrid-admin-linux-el7    linux-x64-el7 (glibc 2.17: RHEL/CentOS 7)
 *   dist/executables/cubrid-admin-linux-arm64  linux-arm64
 *   dist/executables/cubrid-admin-macos        macos-x64
 *   dist/executables/cubrid-admin-macos-arm64  macos-arm64
 *   dist/executables/cubrid-admin.exe          windows-x64
 *
 * NODE_VERSION is the only Node.js the executables use. The blob is generated by
 * that same version, downloaded for the build machine, never by the Node.js that
 * runs this script: a SEA blob only works in the Node.js version that made it.
 * Every download is checked against the SHA-256 pinned below (NODE_SHA256), taken
 * from the release's SHASUMS256.txt when NODE_VERSION was set. Changing
 * NODE_VERSION means updating those pins in the same reviewed change. The el7
 * target uses the same version's glibc 2.17 build from unofficial-builds.nodejs.org
 * (the Node.js project's builds for older Linux); the official Linux builds
 * need glibc 2.28.
 *
 * Run after the API server and web builds and scripts/copy-web-to-api.mjs:
 *   node scripts/build-server-sea.mjs [--target linux-x64] [--target ...]
 * The macOS targets need a macOS build machine (codesign): elsewhere a build
 * of all targets leaves it out with a note, and asking for it fails.
 */

import { execFileSync } from 'child_process';
import { createHash } from 'crypto';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

export const NODE_VERSION = 'v24.22.2';

// SHA-256 of every Node.js file used: the targets and the build machines.
// From https://nodejs.org/dist/v24.22.2/SHASUMS256.txt and
// https://unofficial-builds.nodejs.org/download/release/v24.22.2/SHASUMS256.txt.
const NODE_SHA256 = {
  'node-v24.22.2-linux-x64.tar.xz': '48cc0e21e048790e54c0cf5749c2725005313d652651c40b7a21feb9697aaf75',
  'node-v24.22.2-linux-arm64.tar.xz': 'eb187837a2230d4047161ac0be008584e16b46f726e9c9490ee35dc6b17d9ba8',
  'node-v24.22.2-linux-x64-glibc-217.tar.xz': '2644f0845671e149b8b0705a4fdcca2993995348618dc98c681ba0c7cdf604d2',
  'node-v24.22.2-darwin-x64.tar.gz': 'd5e336d588c45be0c37dbd52cc29895593009ca4997a77a1fd02815131ed0e52',
  'node-v24.22.2-darwin-arm64.tar.gz': 'aa9549349e47dffaa42dcf95d6e06ade8c4bdafc980979883b88767670df385a',
  'win-x64/node.exe': '1c331340fa6cac5e4294725959070a143fa0507195a78ad77eed7943f719aac9',
};

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const SERVER = path.join(ROOT, 'dist', 'apps', 'api-server');
const OUT = path.join(ROOT, 'dist', 'executables');
const CACHE = path.join(ROOT, 'node_modules', '.cache', 'sea-node', NODE_VERSION);
const WORK = path.join(ROOT, 'dist', 'sea');
const DIST_URL = `https://nodejs.org/dist/${NODE_VERSION}`;
const UNOFFICIAL_URL = `https://unofficial-builds.nodejs.org/download/release/${NODE_VERSION}`;
const SEA_FUSE = 'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2';

const TARGETS = {
  'linux-x64': { archive: `node-${NODE_VERSION}-linux-x64.tar.xz`, output: 'cubrid-admin-linux' },
  'linux-x64-el7': {
    archive: `node-${NODE_VERSION}-linux-x64-glibc-217.tar.xz`,
    site: UNOFFICIAL_URL,
    output: 'cubrid-admin-linux-el7',
  },
  'linux-arm64': { archive: `node-${NODE_VERSION}-linux-arm64.tar.xz`, output: 'cubrid-admin-linux-arm64' },
  'macos-x64': { archive: `node-${NODE_VERSION}-darwin-x64.tar.gz`, output: 'cubrid-admin-macos', macos: true },
  'macos-arm64': { archive: `node-${NODE_VERSION}-darwin-arm64.tar.gz`, output: 'cubrid-admin-macos-arm64', macos: true },
  'windows-x64': { file: 'win-x64/node.exe', output: 'cubrid-admin.exe', windows: true },
};

const HOSTS = {
  'darwin-arm64': `node-${NODE_VERSION}-darwin-arm64.tar.gz`,
  'darwin-x64': `node-${NODE_VERSION}-darwin-x64.tar.gz`,
  'linux-x64': `node-${NODE_VERSION}-linux-x64.tar.xz`,
  'linux-arm64': `node-${NODE_VERSION}-linux-arm64.tar.xz`,
  'win32-x64': 'win-x64/node.exe',
};

const run = (command, args, options = {}) => execFileSync(command, args, { stdio: 'inherit', ...options });

async function download(url) {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`Download failed (${response.status}): ${url}`);
  }
  return Buffer.from(await response.arrayBuffer());
}

function expectedSha256(file) {
  const hash = NODE_SHA256[file];
  if (!hash) {
    throw new Error(`No pinned SHA-256 for ${file} (Node.js ${NODE_VERSION}): add it to NODE_SHA256.`);
  }
  return hash;
}

/** The release file, downloaded once into the cache and checked against its pinned SHA-256. */
async function releaseFile(file, site = DIST_URL) {
  const cached = path.join(CACHE, file);
  const expected = expectedSha256(file);
  if (!fs.existsSync(cached) || createHash('sha256').update(fs.readFileSync(cached)).digest('hex') !== expected) {
    console.log(`  download ${site}/${file}`);
    const body = await download(`${site}/${file}`);
    const actual = createHash('sha256').update(body).digest('hex');
    if (actual !== expected) {
      throw new Error(`SHA-256 mismatch for ${file}: expected ${expected}, got ${actual}`);
    }
    fs.mkdirSync(path.dirname(cached), { recursive: true });
    fs.writeFileSync(cached, body);
  }
  return cached;
}

/** The node binary of a release file (an archive, or node.exe itself), copied to `to`. */
async function nodeBinary(file, to, site) {
  const source = await releaseFile(file, site);
  fs.rmSync(to, { force: true });
  fs.mkdirSync(path.dirname(to), { recursive: true });
  if (file.endsWith('.exe')) {
    fs.copyFileSync(source, to);
  } else {
    const folder = path.basename(file).replace(/\.tar\.(gz|xz)$/, '');
    const extractDir = path.join(WORK, 'extract', folder);
    fs.rmSync(extractDir, { recursive: true, force: true });
    fs.mkdirSync(extractDir, { recursive: true });
    run('tar', ['-xf', source, '-C', extractDir, `${folder}/bin/node`]);
    fs.copyFileSync(path.join(extractDir, folder, 'bin', 'node'), to);
  }
  fs.chmodSync(to, 0o755);
  return to;
}

function listFiles(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    if (entry.name.startsWith('.')) return [];
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? listFiles(full) : [full];
  });
}

/**
 * Removes the Authenticode signature of a PE file (the certificate table at the
 * end of the file and the directory entry pointing at it). Injecting into a
 * signed node.exe would otherwise leave a broken signature.
 */
function removeWindowsSignature(file) {
  const data = fs.readFileSync(file);
  const pe = data.readUInt32LE(0x3c);
  if (data.toString('latin1', pe, pe + 4) !== 'PE\0\0') {
    throw new Error(`${file} is not a PE file`);
  }
  const optional = pe + 24;
  const magic = data.readUInt16LE(optional);
  const directories = optional + (magic === 0x20b ? 112 : 96);
  const securityEntry = directories + 4 * 8;
  const offset = data.readUInt32LE(securityEntry);
  const size = data.readUInt32LE(securityEntry + 4);
  if (offset === 0 || size === 0) {
    return false;
  }
  if (offset + size !== data.length) {
    throw new Error(`${file}: the signature is not at the end of the file`);
  }
  data.writeUInt32LE(0, securityEntry);
  data.writeUInt32LE(0, securityEntry + 4);
  fs.writeFileSync(file, data.subarray(0, offset));
  return true;
}

async function main() {
  const args = process.argv.slice(2);
  const requested = args.flatMap((arg, i) => (args[i - 1] === '--target' ? [arg] : []));
  let targets = requested.length > 0 ? requested : Object.keys(TARGETS);
  for (const target of targets) {
    if (!TARGETS[target]) {
      throw new Error(`Unknown target ${target}. Use ${Object.keys(TARGETS).join(', ')}.`);
    }
    if (TARGETS[target].macos && process.platform !== 'darwin' && requested.length > 0) {
      throw new Error(`${target} needs a macOS build machine (the binary is re-signed with codesign).`);
    }
  }
  if (process.platform !== 'darwin') {
    const skipped = targets.filter((target) => TARGETS[target].macos);
    if (skipped.length > 0) {
      console.log(`  skipped ${skipped.join(', ')}: it needs a macOS build machine (codesign)`);
      targets = targets.filter((target) => !TARGETS[target].macos);
    }
  }

  const mainJs = path.join(SERVER, 'main.js');
  if (!fs.existsSync(mainJs) || !fs.existsSync(path.join(SERVER, 'public', 'index.html'))) {
    throw new Error('Build the API server and web first, then run scripts/copy-web-to-api.mjs.');
  }

  const hostFile = HOSTS[`${process.platform}-${process.arch}`];
  if (!hostFile) {
    throw new Error(`No Node.js ${NODE_VERSION} download for this build machine (${process.platform}-${process.arch}).`);
  }
  fs.rmSync(WORK, { recursive: true, force: true });
  fs.mkdirSync(WORK, { recursive: true });
  const hostNode = await nodeBinary(hostFile, path.join(WORK, 'host', process.platform === 'win32' ? 'node.exe' : 'node'));
  const hostVersion = execFileSync(hostNode, ['--version'], { encoding: 'utf8' }).trim();
  if (hostVersion !== NODE_VERSION) {
    throw new Error(`The downloaded Node.js reports ${hostVersion}, expected ${NODE_VERSION}.`);
  }

  // Everything pkg embedded before: the web screens (public/) and assets/.
  const assets = {};
  for (const folder of ['public', 'assets']) {
    for (const file of listFiles(path.join(SERVER, folder))) {
      assets[path.relative(SERVER, file).split(path.sep).join('/')] = file;
    }
  }
  const blob = path.join(WORK, 'server.blob');
  const config = path.join(WORK, 'sea-config.json');
  fs.writeFileSync(
    config,
    JSON.stringify(
      {
        // Relative to the server build folder (the cwd below): the blob keeps
        // this name as the script's file name, shown in stack traces, so an
        // absolute path would put the build machine's folders in the executable.
        main: 'main.js',
        output: blob,
        disableExperimentalSEAWarning: true,
        // Code cache and snapshots are tied to the platform that made them;
        // without them one blob serves every target.
        useSnapshot: false,
        useCodeCache: false,
        assets,
      },
      null,
      2
    )
  );
  console.log(`  blob: ${Object.keys(assets).length} embedded files, made by Node.js ${hostVersion}`);
  run(hostNode, ['--experimental-sea-config', config], { cwd: SERVER });

  fs.mkdirSync(OUT, { recursive: true });
  const postject = path.join(ROOT, 'node_modules', 'postject', 'dist', 'cli.js');
  for (const target of targets) {
    const spec = TARGETS[target];
    const output = path.join(OUT, spec.output);
    await nodeBinary(spec.archive ?? spec.file, output, spec.site);
    if (spec.macos) {
      run('codesign', ['--remove-signature', output]);
    }
    if (spec.windows && removeWindowsSignature(output)) {
      console.log(`  ${spec.output}: removed the Node.js Authenticode signature (the executable is unsigned)`);
    }
    run(process.execPath, [
      postject,
      output,
      'NODE_SEA_BLOB',
      blob,
      '--sentinel-fuse',
      SEA_FUSE,
      ...(spec.macos ? ['--macho-segment-name', 'NODE_SEA'] : []),
    ]);
    if (spec.macos) {
      run('codesign', ['--sign', '-', '--force', output]);
    }
    console.log(`dist/executables/${spec.output}  (${target}, Node.js ${NODE_VERSION}, ${(fs.statSync(output).size / 1048576).toFixed(1)} MB)`);
  }
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
